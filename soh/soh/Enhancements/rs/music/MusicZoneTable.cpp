/*
 * The world-level music zone file (sturdy-bassoon#90 P1). This is the ONLY place zones are
 * authored. `npm run gen:music-zones` (from tools/grid-scene-tool) turns it into the block
 * between the BEGIN/END markers in
 * Shipwright/soh/soh/Enhancements/rs/music/MusicZoneTable.cpp. Never hand-edit that block:
 * the next generator run overwrites it. The format it emits is documented in MusicZones.h.
 *
 * TWO THINGS LIVE IN THIS FILE AND THEY HAVE OPPOSITE LIFETIMES.
 *
 * The FORMAT is permanent: map squares and rects in RS absolute tiles, priorities, the fallback,
 * the optional scene binding, the first-visit flag, the per-scene opt-in, the track list and its
 * durations. Build on it.
 *
 * The CONTENT below was a throwaway POC and most of it HAS now been deleted. See
 * content_status.
 *
 * AUTHOR A ZONE BY MAP SQUARE: `"squares": ["50,50"]`, keys of the world matrix named by
 * `matrix` above. Each expands to that square's 64x64-tile rect, so the C and the director see
 * nothing new - but "50,50" is a square the matrix calls Lumbridge, where four tile numbers are
 * four numbers nobody can check. #90 P1 planned exactly this: a chunk IS a rect, so zones are
 * chunk-aligned first and un-aligned one rect at a time as the world fills in. `rects` is still
 * there for that un-aligning, and a zone may use both.
 *
 * THERE IS A PICTURE OF THIS FILE: tools/music/zone-map.svg, drawn over the world matrix's named
 * chunks by `npm run gen:zone-map` (#90 P4). Look at it before and after changing what a zone
 * covers. A square key or a rect says WHERE in numbers; the map is what shows which PLACE that
 * is, how it sits against its neighbours, and whether anybody has built there yet. Re-render it
 * in the same change; `npm run gen:zone-map -- --check` fails when it is stale.
 */

/*
 * MOST OF THIS FILE IS REAL PLACEMENT NOW, AND WHAT IS NOT IS DELIBERATE.
 *
 * P0's PRECEDENT IS SUPERSEDED. Rects used to be named after the authoring fixture and NEVER
 * after a RuneScape place - settlement, west_fields, north_march rather than lumbridge - because
 * nothing recorded where a grid-tool map sat in the world, so a place name would have been a
 * false premise somebody downstream would inherit. That reason is gone: #92, landed as #173's
 * world matrix, is the thing that records it. A zone named `lumbridge` over the square the matrix
 * itself calls Lumbridge is a checkable claim rather than a guess. NAME ZONES AFTER PLACES, and
 * do not reinstate the old rule - this paragraph is here so nobody re-derives it from the names
 * in P0's run records.
 *
 * WHICH GROUND IS REAL IS THE MATRIX'S ANSWER, NOT THIS FILE'S, and it answers a narrower
 * question than it looks. world/f2p.json flags each cell `terrain: real | standin`, which is
 * about the HEIGHT FIELD bake - it says nothing about whether anybody has built there. The two
 * barely overlap today: every chunk with authored buildings on it is flagged `standin`. The zone
 * map shades by drawn content for exactly that reason. So `lumbridge` and `draynor` are the right
 * music over placeholder ground, which is honest for now and worth not forgetting.
 *
 * THE PLACEMENT IS REAL FOR THREE CHUNKS ACROSS TWO ZONES (2026-10-17/18). P1's fixture rects -
 * `settlement`, `west_fields`, `north_march`, `settlement_core` - are DELETED. They were named
 * after the settlement fixture and drawn before anything recorded where a map sat in the world,
 * and once #173 stitched the overworld the P4 map showed them covering Falador and the Dwarven
 * Mine while Lumbridge had no zone at all. `lumbridge` replaces them on the square the matrix
 * calls Lumbridge, with the six imported tracks (#91); `draynor` covers the two squares Draynor's
 * buildings straddle, with a seventh. The owner walked both and approved them.
 *
 * EVERYWHERE ELSE IS THE FALLBACK ON PURPOSE (owner, 2026-10-17): only Lumbridge's and Draynor's
 * music has been imported, so the rest of the world playing one vanilla track is an honest
 * placeholder rather than an omission. `wilderness` and `test_map_interior` keep vanilla ids,
 * which is also what keeps the mixed vanilla/imported format exercised in-game. Filling in the
 * other 34 chunks is #244.
 *
 * NOTE WHAT THIS COST: the two fixture terrain scenes are still opted in (see scenes) and now
 * play only the fallback, so the zone boundary a run can test against has moved to
 * SCENE_F2P_OVERWORLD. Its Lumbridge chunk centres on OoT (3860, 3820) per its world include.
 *
 * What made the swap cheap, and still does, is the coordinate frame: a rect authored against a
 * fixture lives in the same frame as one authored against real Falador later. Replacing content
 * is editing rows in this file, never migrating a format.
 */

/*
 * RS ABSOLUTE SURFACE TILES, y increasing NORTH. Not OoT world units, and not the terrain
 * toolchain's local 0..383 tile coordinates - both of those move when a bake window changes or
 * the world extent grows. RS's frame is anchored by Jagex and never moves.
 *
 * Anchor: RS (2944, 3519) == terrain tile (0, 0), so rsX = 2944 + tileX and rsY = 3519 - tileY.
 * The 6x6-chunk terrain extent covers RS x 2944..3327, y 3136..3519. Verified against the OSRS
 * Wiki's own map data in docs/decisions/2026-09-08-rs-terrain-coordinate-anchor.md, which also
 * records what that verification does NOT pin (map-square granularity, not tile).
 */

/*
 * THIS GENERATOR PERFORMS NO AXIS FLIP, AND MUST NOT GROW ONE.
 *
 * Its input (this file) and its output (the C table) are both in RS tiles, y north. Nothing to
 * convert. The single flip in the whole feature is RsMusicZones' WorldToRs() in
 * ZoneDirector.cpp, which turns OoT world Z (grows south) into RS y (grows north) at runtime.
 *
 * If someone later wants to author a rect in terrain-tile coordinates as a convenience, that
 * adds a SECOND negation, in a second place, and the two will disagree the first time one of
 * them is edited. Convert on the way in by hand and write the RS numbers here instead.
 */

/*
 * 1. DRAW A RECT TO THE VISUAL EDGE A PLAYER READS AS THE EDGE OF THE PLACE, NOT TO THE
 * AUTHORED FOOTPRINT OF THE GRID-TOOL PROJECT THAT CONTAINS IT.
 *
 * This is the first authoring rule the feature has produced from somebody listening to it
 * (#90, human tuning pass 2026-09-09). P0's `settlement` rect was the composited project's
 * footprint - terrain tiles x 56..118, y 64..143 - but the settlement's walls sit INSIDE
 * that footprint, so the music changed in open ground several tiles outside the visible
 * wall and there was no visual cue for where it happened. A project footprint is an
 * authoring convenience; it is not a thing the player can see.
 *
 * The `settlement` rect below is drawn to the wall instead - see its `derivation`.
 *
 * 2. Overlap is legal and is the intended way to nest. A high-priority rect sitting inside a
 * low-priority one is how you get 'the keep, inside the town, inside the fields' without
 * carving donut-shaped rect unions by hand. Coverage is total because exactly one zone
 * carries `fallback`.
 *
 * 3. A zone with an empty `tracks` list is authored SILENCE, and that is a legitimate choice.
 * It is not the same as leaving a hole - a hole means no zone matched, which only happens
 * if the fallback is removed.
 *
 * 4. A `firstVisitFlag` is serialized into save files. Its number is reserved BY HAND in
 * Shipwright's rs/quest/WorldFlagIds.h and named here; the generator never invents one and
 * refuses a name that is not in that header. POC zones take debug-band flags because their
 * content is going away; a real zone takes a production-band flag.
 *
 * 5. Y bands (`yMinUnits` / `yMaxUnits`, OoT world units) are for 'which floor of a building'.
 * Vertical space above ground inherits the ground zone, so leave them out unless you mean
 * it. Underground is separate scenes and binds by `sceneId` instead.
 *
 * 6. WITHIN A ZONE, EITHER EVERY TRACK CARRIES A `lengthSec` OR NONE OF THEM DOES. The
 * first-visit track counts as one of the zone's tracks for this. 0 means 'plays until
 * stopped', so a mixed list advances happily until it draws the 0 and then stops advancing
 * for the rest of the session - a dead end that looks exactly like the feature being
 * unfinished. The generator refuses the mix.
 *
 * 7. IF A ZONE HAS A FIRST-VISIT OPENER AND THE OPENER IS ALSO IN THE NORMAL TRACK LIST, the
 * shuffle bag will not follow the opener with itself - playing the opener counts as the
 * zone's just-played track for the back-to-back guard. That is a property worth relying on:
 * it means the intended opener can be an ordinary member of the rotation afterwards without
 * the first visit sounding like a stutter. `settlement` below is authored that way on
 * purpose, because it is the only arrangement in which the guard is observable.
 */

/*
 * A TRACK ENTRY IS EITHER A VANILLA `seqId` OR AN IMPORTED `rsTrack`, NEVER BOTH AND NEVER
 * NEITHER. The format keeps both on purpose (owner, 2026-09-17): RS has no music for a test map,
 * and an un-imported place still needs something to play.
 *
 * A DURATION IS STILL A DURATION TABLE, NOT END-OF-TRACK DETECTION - #90 section 9 chose it
 * deliberately - but the two halves of the union mean different things by it.
 *
 * For a vanilla `seqId` you write `lengthSec`, in whole seconds, and it is a POLICY: 'let this
 * play for about this long, then move on', because the sequence data loops and would not end on
 * its own. (That vanilla BGM never ends is recorded as INFERRED rather than byte-verified, in
 * AUDIO_SYSTEM.md section 7; nothing here depends on resolving it, which is the point of a
 * duration table.) The advance is a cut into a song still playing, so it takes the global
 * RsMusicFadeOutSec.
 *
 * For an `rsTrack` you write NOTHING but the id. Its duration is `audioSec` from
 * rs-tracks.record.json - a MEASUREMENT of where the music ends - and the generator refuses a
 * `lengthSec` beside it, because a number here would be a second answer that agrees until the
 * next re-import. Its placeholder, its end fade and its archive path come from the same record.
 *
 * WHY audioSec AND NOT THE SEQUENCE'S LENGTH. A Looped="false" sequence runs about 2% past its
 * authored `Length` plus up to 1.25 s of tick rounding, so the player is still enabled for a
 * second or two after the music has stopped. Advancing on quiet would put that silence in front
 * of every track change.
 *
 * AND THE END FADE IS THE TRACK'S, NOT THE DIRECTOR'S. RS exports end inconsistently - Flute
 * Salad carries ~10 s of baked fade-out, Autumn Voyage stops dead - so each track records an
 * `endFadeSec` (5 by default, authored by ear in rs-tracks.json) and the in-zone advance fires
 * that far BEFORE audioSec, fading for exactly that long so the ramp lands on the ending. 0 lets
 * the track's own ending play. Change it with `npm run import:rs-music -- --refresh-record`,
 * never by editing the record: re-encoding is not byte-reproducible.
 *
 * 0 keeps its old meaning, 'plays until stopped', and a zone whose tracks are all 0 never
 * advances at all. That is what every zone did through P1 and it stays valid - `north_march`
 * below is authored that way on purpose so the behaviour has a live example rather than only a
 * sentence. ALL-OR-NOTHING WITHIN A ZONE still holds across the union: an rsTrack always has a
 * duration, so mixing one into a zone of bare NA_BGM_* ids is refused.
 *
 * The director also advances when sequence player 0 goes quiet on its own, whichever comes
 * first. That is opportunistic and never the mechanism: see 'one end-of-track handler, two
 * triggers' in ZoneDirector.h.
 */

